export function decideScent(answers, random = Math.random) {
  const totals = Object.fromEntries(Object.keys(scents).map(id => [id, 0]));
  for (const answer of answers) {
    for (const id of Object.keys(totals)) totals[id] += answer.scores[id] || 1;
  }
  const highest = Math.max(...Object.values(totals));
  let candidates = Object.keys(totals).filter(id => totals[id] === highest);
  if (candidates.length > 1 && answers.length) {
    const lastScores = answers.at(-1).scores;
    const lastHighest = Math.max(...candidates.map(id => lastScores[id] || 1));
    candidates = candidates.filter(id => (lastScores[id] || 1) === lastHighest);
  }
  return candidates[Math.floor(random() * candidates.length)];
}

export function messageIndex(scentId, dateKey, offset = 0) {
  const text = `${scentId}:${dateKey}`;
  let hash = 0;
  for (const character of text) hash = (hash * 31 + character.codePointAt(0)) >>> 0;
  return (hash + offset) % scents[scentId].messages.length;
}
