import assert from 'node:assert/strict';
import { kakaoCardPayload } from '../src/kakao-card.js';
const result = { stone: 'pink', score: 1250, combo: 12, hits: 10 };
const card = kakaoCardPayload(result, 'https://minsung0732.github.io/gid/', 'https://example.com/card.png');
assert.equal(card.objectType, 'feed');
assert.ok(card.content.title.includes('1,250점'));
assert.ok(card.content.description.includes('12콤보'));
assert.equal(new URL(card.buttons[0].link.webUrl).pathname, '/gid/games/');
assert.equal(card.content.imageUrl, 'https://example.com/card.png');
const localCard = kakaoCardPayload(result, 'http://127.0.0.1:5173/', 'https://example.com/card.png');
assert.equal(new URL(localCard.content.link.webUrl).origin, 'https://minsung0732.github.io');
assert.equal(new URL(localCard.buttons[0].link.mobileWebUrl).pathname, '/gid/games/');
console.log('PASS: personalized Kakao card payload and game-list link.');
const { setupKakaoShare } = await import('../src/kakao-share.js');
globalThis.window = { location: { href: 'https://minsung0732.github.io/gid/' } };
let click, prepared = 0, sent = 0, fail = false;
const button = { addEventListener(_,fn){click=fn;}, disabled:false, textContent:'' };
const status = {textContent:''};
const sdk = { Share: { sendDefault(payload){assert.equal(payload.objectType,'feed');sent++;} } };
setupKakaoShare({button,status,canvas:{},getResult:()=>({...result}),loadSdk:async()=>sdk,prepare:async()=>{prepared++;if(fail)throw Error('upload failed');return card;}});
await click(); assert.equal(prepared,1); assert.equal(sent,0); assert.equal(button.disabled,false);
await click(); assert.equal(prepared,1); assert.equal(sent,1);
result.score=1400; await click(); assert.equal(prepared,2); assert.equal(sent,1);
fail=true; result.score=1500; await click(); assert.ok(status.textContent.includes('다시 시도')); assert.equal(button.disabled,false);
console.log('PASS: two-step sharing, cached upload, changed score, upload error fallback.');
